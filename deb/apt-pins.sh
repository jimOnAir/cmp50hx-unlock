#!/bin/bash
# apt-pins.sh — the apt drift protection of cmp50hx-unlock (sourced by
# deb/postinst; the release side is a plain file removal in prerm/postrm so
# removal never depends on /opt files that dpkg may already have deleted).
#
# Why: this package installs the NVIDIA userland with the embedded .run
# (files outside the dpkg database) and ships the kernel modules as a DKMS
# tree. apt happily installs or upgrades Ubuntu's stock NVIDIA driver family
# around that stack and silently shadows it — proven live on llm2 (Oct 2026):
# 615.71.10-1ubuntu1 libnvidia-compute/cfg1/gpucomp/persistenced landed with
# no protection while the 610.43.03 unlock was serving inference.
#
# Why pins and not apt-mark: apt-mark (and any dpkg/apt invocation) needs
# the dpkg database lock that dpkg holds across every maintainer script —
# proven empirically: apt_holds applied from postinst always fails with
# "apt-mark hold <pkg> failed". /etc/apt/preferences.d is a plain file,
# needs no lock, supports the globs the dpkg Conflicts: field cannot, and is
# strictly stronger than a hold: it blocks NEW stock driver installs too,
# not just upgrades. Pin-Priority: -1 keeps already-installed strays but
# freezes them (Candidate: (none)); if a later dist-upgrade drops one, the
# .run-provided file stays functional and a reinstall of this package
# re-stages the userland anyway.
#
# Contract (asserted by tools/smoke-test-deb.sh and the CI hold lifecycle):
#   - every configure rewrites /etc/apt/preferences.d/cmp50hx-unlock,
#     pinning the stock NVIDIA driver family at -1;
#   - 'apt remove/purge cmp50hx-unlock' deletes the file again (prerm does
#     it while /opt exists, postrm is the half-install safety net);
#   - the package itself is deliberately NOT pinned: explicit
#     'apt install ./cmp50hx-unlock_<new>.deb' upgrades always work;
#   - stock packages already on the box are frozen, never removed by us.
#
# The globs mirror deb/preinst's gate plus the bare base names that gate
# deliberately lets through (hard-blocking them in preinst would break
# existing hosts that carry them — see findings.md). Deliberately spared
# (no prefix collision, or the updates are wanted):
#   nvidia-container-* / libnvidia-container* — the Docker GPU runtime
#     must keep receiving updates (no file overlap with our stack);
#   libnvidia-egl-* — EGL external-platform libs used beyond the driver;
#   nvidia-prime — offload scripting, driver-agnostic;
#   linux-firmware-nvidia-* — GSP firmware in use comes from the embedded
#     .run under /lib/firmware/nvidia/<version>/;
#   linux-headers-* — the DKMS tree MUST follow every new kernel.

apt_pins_apply() {
    local pins_file="/etc/apt/preferences.d/cmp50hx-unlock"
    local pins_tmp="${pins_file}.tmp"
    local family_globs=(
        nvidia-driver* nvidia-dkms* nvidia-kernel-* nvidia-utils*
        nvidia-compute-utils* nvidia-headless* nvidia-fabricmanager*
        nvidia-persistenced* nvidia-settings* xserver-xorg-video-nvidia*
        libnvidia-cfg1* libnvidia-compute* libnvidia-gpucomp*
        libnvidia-gl* linux-modules-nvidia*
    )
    local glob

    mkdir -p /etc/apt/preferences.d
    {
        printf '%s\n' \
            '# Generated by the cmp50hx-unlock package — do not edit.' \
            '#' \
            '# The package installs the NVIDIA userland from an embedded .run' \
            '# (files outside the dpkg database) and the patched open kernel' \
            '# modules via DKMS, so apt must never install or upgrade Ubuntu' \
            '# stock NVIDIA driver packages over them (llm2 615-drift incident).' \
            '#' \
            '# To use a stock driver deliberately: sudo apt remove' \
            '# cmp50hx-unlock first — removal deletes this file. Spared from' \
            '# the pins: *container*, libnvidia-egl-*, nvidia-prime,' \
            '# linux-firmware-nvidia*, linux-headers*.'
        for glob in "${family_globs[@]}"; do
            printf 'Package: %s\nPin: version *\nPin-Priority: -1\n\n' "${glob}"
        done
    } > "${pins_tmp}"
    mv "${pins_tmp}" "${pins_file}"

    # no apt-mark state survives from earlier candidates of this design
    rm -f "/var/lib/cmp50hx-unlock/apt-holds"

    apt_pins_summary="${#family_globs[@]} globs pinned at -1 (${pins_file})"
    log "apt pins applied: ${apt_pins_summary}"
}
