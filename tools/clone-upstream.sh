#!/usr/bin/env bash
# Clone the 90HX campaign source corpus into the (git-ignored) work/upstream/
# folder for repo-local analysis, then regenerate the provenance manifest.
#
# READ-ONLY CORPUS: never build or run code from here as part of an llm2
# window without a separate review; these are third-party trees used for
# grepping and cross-referencing (see docs/cmp90hx/SOURCES.md for rationale
# per repo).
#
# Usage: tools/clone-upstream.sh          # clone missing, verify present
set -uo pipefail
cd "$(dirname "$0")/.."
DEST=work/upstream
MANIFEST=docs/cmp90hx/upstream/CLONES.md
mkdir -p "$DEST"

REPOS=(
  "Zagitta/gpu-unlock"                 # pre-driver V67 executor, path #5a carrier
  "KohakuBlueleaf/KohakUnlock"         # TU102 initramfs port + Ampere pointer
  "KohakuBlueleaf/mmapeak"             # benchmark fork (methodology ref)
  "lixiangwuxian/cmpunlocker"          # lineage ROOT (2d10f89 plmTable)
  "lixiangwuxian/170hx_tips"           # GA100 Gen3 guide: RM levers, L1b
  "lixiangwuxian/170hx-rir-tool"       # GA100 RIR fuse writer (FORBIDDEN here)
  "iatethelogs/cmp90hx_pwner"          # Habr author tool; P2P recipe @73bc5ea
  "jdowning100/cmpunlocker"            # rejoin16 Gen2 path (tested 0/49)
  "pearlfortune/cmpunlocker"           # production compute unlock (llm2 fleet)
  "Wh1stle05/cmp90hx"                  # published 2x90HX landings
  "WildFlash1st/cmp90hx-unlock"        # Linux research + EFI pre-OS
  "WildFlash1st/cmp90hx-unlock-for-windows"
  "bendy2/cmp90hx"                     # V67 stockflow origin
  "impacifist/Windows-GPU-UNLOCK"      # Zagitta Windows port
  "haohervchb/Turing-unlock"           # Kohak executor upstream
)

declare -a LINES=() FAILED=()
for r in "${REPOS[@]}"; do
  slug="${r/\//-}"
  d="$DEST/$slug"
  if [[ ! -d "$d/.git" ]]; then
    git clone --quiet --depth 1 --single-branch "https://github.com/$r" "$d" \
      || { FAILED+=("$r"); continue; }
  fi
  sha=$(git -C "$d" rev-parse HEAD)
  date=$(git -C "$d" log -1 --format=%cs)
  LINES+=("| \`$r\` | \`$sha\` | $date | \`$d\` |")
done

{
  echo "# Upstream clone corpus — provenance manifest"
  echo
  echo "Regenerated by \`tools/clone-upstream.sh\` on $(date -u +%F). Clones"
  echo "live in git-ignored \`work/upstream/\`; this manifest is the pinned record."
  echo
  echo "**Read-only analysis corpus.** Nothing here is executed as part of a"
  echo "live window without separate review. Link-by-link rationale and"
  echo "reflection pointers live in [\`docs/cmp90hx/SOURCES.md\`](../SOURCES.md)."
  echo
  echo "| Repo | Pinned HEAD | Commit date | Path |"
  echo "|---|---|---|---|"
  printf '%s\n' "${LINES[@]}"
  if (( ${#FAILED[@]} )); then
    echo
    echo "Failed to clone (verify name/availability):"
    printf -- '- %s\n' "${FAILED[@]}"
  fi
  echo
  echo "Not cloned (recorded in SOURCES.md only): xrip/cmp50hx-unlock (this"
  echo "repo's origin), NVIDIA 610.43.03 archives (\`cache/\`, sha-verified), the"
  echo "campaign patched tree (\`work/build.1vZgdr/source/\`), huggingface AD103."
} > "$MANIFEST"

echo "manifest -> $MANIFEST"
printf '%s\n' "${LINES[@]}" | sed 's/|//g'
if (( ${#FAILED[@]} )); then printf 'FAILED: %s\n' "${FAILED[@]}"; exit 1; fi
